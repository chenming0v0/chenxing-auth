-- 为 user_consents 增加单调递增的状态版本号，使 Redis 缓存能判定自己是否陈旧。
--
-- **背景**（Issue #276）：
-- 撤销与重新授权各自「先写 PostgreSQL（权威），再写 Redis（缓存）」。两条链路交错时
-- 顺序可以反过来：
--
--   1. 撤销：UPDATE revoked_at = now()        （DB 已撤销）
--   2. 重新授权：UPSERT revoked_at = NULL     （DB 已重新授权）
--   3. 重新授权：清除 Redis 缓存标记
--   4. 撤销：SET 缓存标记 = 已撤销            ← 迟到的写入覆盖了正确状态
--
-- 第 4 步留下的标记与数据库事实相反，而读路径命中缓存即短路返回「已撤销」，
-- 于是 refresh / userinfo 在 `revoked_at IS NULL` 的情况下被持续拒绝，
-- 直到缓存键的 TTL（此前是 180 天）到期。
--
-- **解决方案**：
-- 每次状态跃迁（撤销或重新授权）都把 `state_version` 加一，并让写路径把
-- 「产生该结论时的版本号」一起写进 Redis。缓存更新走 Lua 脚本做条件写：
-- 已缓存版本更高时拒绝落盘，因此第 4 步那种迟到写入不再能覆盖第 3 步的结论。
--
-- **为什么是计数器而不是时间戳**：
-- 时间戳依赖多个应用实例的时钟一致，且同一秒内的两次跃迁无法比较大小。
-- 计数器由数据库在同一条 UPDATE / UPSERT 内自增，天然与权威写入原子，
-- 且严格单调；比较逻辑退化为整数大小比较，Lua 侧不需要解析时间格式。
--
-- **默认值 1**：
-- 存量行视为「第 1 版」。缓存键在 Issue #276 中同时换了前缀
-- （`consent-revoked:` → `consent-state:`），因此不存在「旧格式缓存值 + 新版本号」
-- 的比较问题：旧键不再被读取，随自身 TTL 自然回收。
--
-- **兼容性**：
-- 幂等操作：使用 `IF NOT EXISTS`，允许在已执行该迁移的环境中重复运行。
-- 该列只被撤销 / 授权路径读写，不参与任何既有查询的过滤条件。

ALTER TABLE user_consents
    ADD COLUMN IF NOT EXISTS state_version BIGINT NOT NULL DEFAULT 1;
